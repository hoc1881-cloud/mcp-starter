// Helper to generate realistic candle data given current price and volatility
export function generateCandles(basePrice: number, count = 30, volatility = 0.015, trend = 0.002) {
  const candles = [];
  let currentClose = basePrice * (1 - (count * trend) / 2);
  const now = new Date();

  for (let i = count; i >= 0; i--) {
    const timeDate = new Date(now.getTime() - i * 15 * 60 * 1000);
    const timeStr = timeDate.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    
    const change = currentClose * volatility * (Math.random() - 0.48);
    const open = currentClose;
    const close = Math.max(0.001, open + change);
    const high = Math.max(open, close) + Math.random() * currentClose * volatility * 0.5;
    const low = Math.min(open, close) - Math.random() * currentClose * volatility * 0.5;
    const volume = Math.floor(basePrice * 1000 * (0.8 + Math.random() * 1.5));

    candles.push({
      time: timeStr,
      open: Number(open.toFixed(basePrice < 10 ? 4 : 2)),
      high: Number(high.toFixed(basePrice < 10 ? 4 : 2)),
      low: Number(low.toFixed(basePrice < 10 ? 4 : 2)),
      close: Number(close.toFixed(basePrice < 10 ? 4 : 2)),
      volume,
    });

    currentClose = close;
  }
  return candles;
}

// Helper to generate sparkline array from candle close prices
export function candlesToSparkline(candles: ReturnType<typeof generateCandles>): number[] {
  return candles.map((c) => c.close);
}

